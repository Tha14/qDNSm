#!/usr/bin/env python3
"""Generate the compiled GameSpy supported-title table.

The generated header is checked in. The build does not run Python; run this
script whenever data/gamespy-supported-titles.ini changes.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE_PATH = ROOT / "data" / "gamespy-supported-titles.ini"
HEADER_PATH = ROOT / "src" / "Core" / "OpenSpySupportedTitles.generated.hpp"

TITLE_ID_RE = re.compile(r"^[A-Za-z]{4}[0-9]{5}$")


class TitleListError(Exception):
    pass


def parse_titles(path):
    titles = []
    seen = set()

    with path.open("r", encoding="utf-8", newline="") as handle:
        for line_number, raw in enumerate(handle, 1):
            line = raw.strip()

            if not line or line.startswith("#") or line.startswith(";"):
                continue

            if "#" in line:
                line = line.split("#", 1)[0].strip()
            if not line:
                continue

            if not TITLE_ID_RE.fullmatch(line):
                raise TitleListError(
                    f"{path}:{line_number}: invalid TitleID {line!r}; expected 4 letters and 5 digits"
                )

            title_id = line.upper()
            if title_id in seen:
                raise TitleListError(
                    f"{path}:{line_number}: duplicate TitleID {title_id}"
                )

            seen.add(title_id)
            titles.append(title_id)

    return titles


def render(titles):
    lines = [
        "// Generated by tools/gen-supported-titles.py. Do not edit.",
        "#pragma once",
        "",
    ]

    if titles:
        lines.append("static const char* const kSupportedGameTitleIds[] = {")
        for title_id in titles:
            lines.append(f'    "{title_id}",')
        lines.append("};")
        lines.append("")
        lines.append(
            f"static const unsigned kSupportedGameTitleIdCount = {len(titles)};"
        )
    else:
        lines.append(
            "static const char* const kSupportedGameTitleIds[] = { nullptr };"
        )
        lines.append("")
        lines.append("static const unsigned kSupportedGameTitleIdCount = 0;")

    return "\n".join(lines) + "\n"


def main():
    check = "--check" in sys.argv[1:]

    try:
        titles = parse_titles(SOURCE_PATH)
    except (OSError, TitleListError) as error:
        print(error, file=sys.stderr)
        return 1

    output = render(titles)

    if check:
        try:
            current = HEADER_PATH.read_text(encoding="utf-8")
        except OSError as error:
            print(error, file=sys.stderr)
            return 1

        if current != output:
            print(
                f"{HEADER_PATH} is stale; run tools/gen-supported-titles.py",
                file=sys.stderr,
            )
            return 1

        print(f"{HEADER_PATH} is up to date")
        return 0

    HEADER_PATH.write_text(output, encoding="utf-8", newline="\n")
    print(f"wrote {HEADER_PATH} ({len(titles)} title(s))")
    return 0


if __name__ == "__main__":
    sys.exit(main())
