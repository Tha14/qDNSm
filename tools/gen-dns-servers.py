#!/usr/bin/env python3
"""Generate the compiled default DNS server list from data/dns-servers.ini.

The generated header is checked in. The build does not run Python; run this
script whenever the managed DNS list changes.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE_PATH = ROOT / "data" / "dns-servers.ini"
HEADER_PATH = ROOT / "src" / "Core" / "DefaultDnsServers.generated.hpp"

sys.path.insert(0, str(ROOT / "data"))

from validate import ValidationError, parse_dns_file  # noqa: E402


def cpp_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(entries):
    lines = [
        "// Generated by tools/gen-dns-servers.py. Do not edit.",
        "#pragma once",
        "",
        "static const DefaultDnsServer DEFAULT_DNS_SERVERS[] =",
        "{",
    ]

    for entry in entries:
        lines.append(
            f'    {{ {cpp_string(entry["name"])}, {cpp_string(entry["primary"])} }},'
        )

    lines.extend([
        "};",
        "",
    ])

    return "\n".join(lines)


def main():
    check = "--check" in sys.argv[1:]

    try:
        dns = parse_dns_file(SOURCE_PATH)
    except (OSError, ValidationError) as error:
        print(error, file=sys.stderr)
        return 1

    output = render(dns["entries"])

    if check:
        try:
            current = HEADER_PATH.read_text(encoding="utf-8")
        except OSError as error:
            print(error, file=sys.stderr)
            return 1

        if current != output:
            print(
                f"{HEADER_PATH} is stale; run tools/gen-dns-servers.py",
                file=sys.stderr,
            )
            return 1

        print(f"{HEADER_PATH} is up to date")
        return 0

    HEADER_PATH.write_text(output, encoding="utf-8", newline="\n")
    print(f"wrote {HEADER_PATH} ({len(dns['entries'])} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
